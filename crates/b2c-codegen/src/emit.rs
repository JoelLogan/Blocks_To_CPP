impl Emitter {
    /// An emitter at global scope.
    fn new(p: crate::printer::Printer) -> Self {
        Emitter {
            p,
            region: Region::default(),
        }
    }

    /// Closes and opens namespaces until `target`'s are open: the open ones
    /// that `target` does not share are closed, innermost first, then
    /// `target`'s other ones are opened, each `namespace n {` on a line of
    /// its own, and an empty line before what follows. Whether anything
    /// changed.
    fn enter(&mut self, target: &Region) -> bool {
        if self.region == *target {
            return false;
        }
        let current = std::mem::take(&mut self.region);
        // The user namespaces both have, from the outermost; the anonymous
        // one is innermost, so it is kept only when everything else is.
        let common = current
            .namespaces
            .iter()
            .zip(&target.namespaces)
            .take_while(|(a, b)| a == b)
            .count();
        let keep_anonymous = current.anonymous
            && target.anonymous
            && common == current.namespaces.len()
            && common == target.namespaces.len();
        // The closing lines, innermost first, after an empty line.
        let mut closing: Vec<Option<&Ident>> = Vec::new();
        if current.anonymous && !keep_anonymous {
            closing.push(None);
        }
        closing.extend(current.namespaces[common..].iter().rev().map(Some));
        if !closing.is_empty() {
            self.p.section();
        }
        for name in closing {
            self.p.fixed("}  // namespace");
            if let Some(name) = name {
                self.p.fixed(" ");
                self.p.ident(name);
            }
            self.p.newline();
        }
        if target.namespaces.len() > common || (target.anonymous && !keep_anonymous) {
            self.p.section();
            for name in &target.namespaces[common..] {
                self.p.fixed("namespace ");
                self.p.ident(name);
                self.p.fixed(" {");
                self.p.newline();
            }
            if target.anonymous && !keep_anonymous {
                self.p.fixed("namespace {");
                self.p.newline();
            }
        }
        self.region = target.clone();
        true
    }

    /// A type: keywords and library names as generator text, user types as
    /// identifiers joined by `::`, template arguments in `<…>` separated by
    /// `, ` (`std::map<std::string, std::vector<int>>`).
    fn ty(&mut self, ty: &CType) {
        match ty {
            CType::Lib(lib, args) => {
                self.p.fixed(lib.cpp_name());
                if !args.is_empty() {
                    self.p.fixed("<");
                    for (index, arg) in args.iter().enumerate() {
                        if index > 0 {
                            self.p.fixed(", ");
                        }
                        self.ty(arg);
                    }
                    self.p.fixed(">");
                }
            }
            CType::Named(path) => self.qualified(path),
            other => self.p.fixed(other.keyword().unwrap_or("int /* error */")),
        }
    }

    /// Identifiers joined by `::`.
    fn qualified(&mut self, path: &[Ident]) {
        for (index, part) in path.iter().enumerate() {
            if index > 0 {
                self.p.fixed("::");
            }
            self.p.ident(part);
        }
    }

    /// `ret name(params)`, with the parameters' default values in a
    /// declaration (w2.md §2.8), never in a definition.
    fn signature(&mut self, function: &CFunction, defaults: bool) {
        self.ty(&function.ret);
        self.p.fixed(" ");
        self.p.ident(&function.name);
        self.p.fixed("(");
        for (index, param) in function.params.iter().enumerate() {
            if index > 0 {
                self.p.fixed(", ");
            }
            self.param(param, defaults);
        }
        self.p.fixed(")");
    }

    /// `int x`, `int& x` or `const std::string& x`, then `= value` when
    /// `default` and the parameter has a default value.
    fn param(&mut self, param: &CParam, default: bool) {
        let start = self.p.position();
        if param.style == ParamStyle::ConstRef {
            self.p.fixed("const ");
        }
        self.ty(&param.ty);
        match param.style {
            ParamStyle::Value => {}
            ParamStyle::Ref | ParamStyle::ConstRef => self.p.fixed("&"),
            ParamStyle::PointerArray => self.p.fixed("*"),
        }
        self.p.fixed(" ");
        self.p.ident(&param.name);
        if param.style == ParamStyle::PointerArray {
            self.p.fixed("[]");
        }
        if default && let Some(value) = &param.default {
            self.p.fixed(" = ");
            self.expr(value);
        }
        self.p.map(start, &param.origin);
    }

    /// A forward declaration: `ret name(params);`.
    fn declaration(&mut self, function: &CFunction) {
        let start = self.p.position();
        self.signature(function, true);
        self.p.fixed(";");
        self.p.map(start, &function.origin);
        self.p.newline();
    }

    /// A function definition with its comment.
    fn definition(&mut self, function: &CFunction) {
        let start = self.p.position();
        if let Some(comment) = &function.comment {
            self.p.comment(comment);
        }
        self.signature(function, false);
        self.p.fixed(" ");
        self.block(&function.body);
        self.p.map(start, &function.origin);
        self.p.newline();
    }

    /// A user type's definition and the free functions generated for it.
    fn type_def(&mut self, def: &CTypeDef) {
        match def {
            CTypeDef::Forward(name) => {
                self.p.fixed("struct ");
                self.p.ident(name);
                self.p.fixed(";");
                self.p.newline();
            }
            CTypeDef::Struct(def) => self.struct_def(def),
            CTypeDef::Enum(def) => self.enum_def(def),
        }
    }

    /// `struct S { fields; operators };`. The fields, the defaulted `<=>`
    /// and each hidden friend are separated by an empty line.
    fn struct_def(&mut self, def: &CStruct) {
        let start = self.p.position();
        if let Some(comment) = &def.comment {
            self.p.comment(comment);
        }
        self.p.fixed("struct ");
        self.p.ident(&def.name);
        self.p.fixed(" {");
        self.p.newline();
        self.p.indent();
        for field in &def.fields {
            let field_start = self.p.position();
            self.ty(&field.ty);
            self.p.fixed(" ");
            self.p.ident(&field.name);
            self.init(&field.init);
            self.p.fixed(";");
            self.p.map(field_start, &field.origin);
            self.p.newline();
        }
        // No empty line right after the opening brace.
        let mut separate = !def.fields.is_empty();
        if def.defaulted_compare {
            if separate {
                self.p.section();
            }
            separate = true;
            self.p.fixed("auto operator<=>(const ");
            self.p.ident(&def.name);
            self.p.fixed("&) const = default;");
            self.p.newline();
        }
        for friend in &def.friends {
            if separate {
                self.p.section();
            }
            separate = true;
            self.generated(friend, std::slice::from_ref(&def.name));
        }
        self.p.dedent();
        self.p.fixed("};");
        self.p.map(start, &def.origin);
        self.p.newline();
    }

    /// `enum class E { A, B };`, then its generated functions, each in a
    /// section of its own: `operator<<` beside the enum, so that
    /// argument-dependent lookup finds it, and `b2c::to_text` at global
    /// scope, with the enclosing namespaces closed before it and opened
    /// again after it (w3-modules.md §1.7).
    /// The namespaces closed for `b2c::to_text` are opened again by
    /// whatever is printed next in them.
    fn enum_def(&mut self, def: &CEnum) {
        let region = self.region.clone();
        self.enum_definition(def);
        for function in &def.functions {
            if function.kind == Generated::EnumToString {
                // Beside the decimal helper of that name, in the global
                // `b2c` namespace (w2.md §2.11).
                self.enter(&Region::default());
                self.p.section();
                self.p.fixed("namespace b2c {");
                self.p.newline();
                self.p.section();
                self.p.fixed("inline ");
                self.generated(function, &def.qualified_name());
                self.p.section();
                self.p.fixed("}  // namespace b2c");
                self.p.newline();
            } else {
                self.enter(&region);
                self.p.section();
                self.generated(function, std::slice::from_ref(&def.name));
            }
        }
    }

    /// `enum class E { A, B };` alone, with its comment.
    fn enum_definition(&mut self, def: &CEnum) {
        let start = self.p.position();
        if let Some(comment) = &def.comment {
            self.p.comment(comment);
        }
        self.p.fixed("enum class ");
        self.p.ident(&def.name);
        self.p.fixed(" {");
        for (index, value) in def.values.iter().enumerate() {
            self.p.fixed(if index == 0 { " " } else { ", " });
            self.p.ident(value);
        }
        self.p.fixed(if def.values.is_empty() { "};" } else { " };" });
        self.p.map(start, &def.origin);
        self.p.newline();
    }

    /// A function generated for the user type `owner`, with its body:
    /// `friend bool operator==(const S& lhs, const S& rhs) { … }`.
    fn generated(&mut self, function: &CGenerated, owner: &[Ident]) {
        if function.kind.is_friend() {
            self.p.fixed("friend ");
        }
        self.p.fixed(function.kind.ret());
        self.p.fixed(" ");
        let (prefix, name) = function.kind.name();
        if let Some(prefix) = prefix {
            self.p.fixed(prefix);
        }
        self.p.fixed(name);
        self.p.fixed("(");
        for (index, kind) in function.kind.params().iter().enumerate() {
            if index > 0 {
                self.p.fixed(", ");
            }
            match kind {
                GeneratedParam::Stream => self.p.fixed("std::ostream&"),
                GeneratedParam::ConstRef => {
                    self.p.fixed("const ");
                    self.qualified(owner);
                    self.p.fixed("&");
                }
                GeneratedParam::Value => self.qualified(owner),
            }
            if let Some(Some(name)) = function.params.get(index) {
                self.p.fixed(" ");
                self.p.ident(name);
            }
        }
        self.p.fixed(") ");
        match (function.kind, function.body.stmts.as_slice()) {
            (
                Generated::Compare(_),
                [
                    CStmt {
                        kind: CStmtKind::Return(Some(value)),
                        ..
                    },
                ],
            ) => {
                self.p.fixed("{");
                self.p.newline();
                self.p.indent();
                self.return_comparison(value);
                self.p.newline();
                self.p.dedent();
                self.p.fixed("}");
            }
            _ => self.block(&function.body),
        }
        self.p.newline();
    }

    /// `return a == b;` for a generated comparison. When the line would be
    /// longer than [`LINE_WIDTH`], the operator starts the next line, under
    /// the left operand:
    ///
    /// ```text
    /// return std::tie(lhs.name, lhs.mark)
    ///        == std::tie(rhs.name, rhs.mark);
    /// ```
    fn return_comparison(&mut self, value: &CExpr) {
        self.p.fixed("return ");
        let column = self.p.position().column;
        // The columns used so far, the value and the `;`.
        let width = column as usize - 1 + flat_width(value) + 1;
        match &value.kind {
            CExprKind::Binary { op, lhs, rhs } if width > LINE_WIDTH => {
                self.expr(lhs);
                self.p.newline_aligned(column);
                self.p.fixed(op.token());
                self.p.fixed(" ");
                self.expr(rhs);
            }
            _ => self.expr(value),
        }
        self.p.fixed(";");
    }

    /// A declarator's initialiser: ` = value`, `{}` or `(args)`.
    fn init(&mut self, init: &Init) {
        match init {
            Init::Value(value) => {
                self.p.fixed(" = ");
                self.expr(value);
            }
            Init::Braces => self.p.fixed("{}"),
            Init::Args(args) => {
                self.p.fixed("(");
                self.args(args);
                self.p.fixed(")");
            }
        }
    }

    /// Arguments or items separated by `, `.
    fn args(&mut self, args: &[CExpr]) {
        for (index, arg) in args.iter().enumerate() {
            if index > 0 {
                self.p.fixed(", ");
            }
            self.expr(arg);
        }
    }

    /// A global variable or constant (w2.md §2.7), with its comment:
    /// `constexpr double kGravity = 9.81;`.
    pub(crate) fn global(&mut self, global: &CGlobal) {
        let start = self.p.position();
        if let Some(comment) = &global.comment {
            self.p.comment(comment);
        }
        self.p.fixed(global.qualifier.prefix());
        self.ty(&global.ty);
        self.p.fixed(" ");
        self.p.ident(&global.name);
        self.init(&global.init);
        self.p.fixed(";");
        self.p.map(start, &global.origin);
        self.p.newline();
    }

    /// A shared global as its module's header declares it (w3-modules.md
    /// §1.7): `extern T name;`, `extern const T name;`, or a `constexpr`
    /// constant's `inline constexpr T name = value;`.
    fn global_declaration(&mut self, global: &CGlobal) {
        let start = self.p.position();
        if let Some(comment) = &global.comment {
            self.p.comment(comment);
        }
        match global.qualifier {
            Qualifier::Constexpr => {
                self.p.fixed("inline constexpr ");
                self.ty(&global.ty);
                self.p.fixed(" ");
                self.p.ident(&global.name);
                self.init(&global.init);
            }
            Qualifier::Const | Qualifier::None => {
                self.p.fixed("extern ");
                self.p.fixed(global.qualifier.prefix());
                self.ty(&global.ty);
                self.p.fixed(" ");
                self.p.ident(&global.name);
            }
        }
        self.p.fixed(";");
        self.p.map(start, &global.origin);
        self.p.newline();
    }

    /// `{`, the statements one level deeper, `}`.
    fn block(&mut self, block: &CBlock) {
        self.p.fixed("{");
        self.p.newline();
        self.p.indent();
        for stmt in &block.stmts {
            self.stmt(stmt);
            self.p.newline();
        }
        self.p.dedent();
        self.p.fixed("}");
    }

    /// A statement with its comment, without the final line break.
    fn stmt(&mut self, stmt: &CStmt) {
        let start = self.p.position();
        if let Some(comment) = &stmt.comment {
            self.p.comment(comment);
        }
        self.stmt_kind(&stmt.kind);
        if let Some(origin) = &stmt.origin {
            self.p.map(start, origin);
        }
    }

    /// The statement itself.
    #[allow(clippy::too_many_lines, reason = "one arm per statement node")]
    fn stmt_kind(&mut self, kind: &CStmtKind) {
        match kind {
            CStmtKind::Decl {
                is_const,
                ty,
                name,
                init,
            } => {
                if *is_const {
                    self.p.fixed("const ");
                }
                self.ty(ty);
                self.p.fixed(" ");
                self.p.ident(name);
                self.init(init);
                self.p.fixed(";");
            }
            CStmtKind::Expr(expr) => {
                self.expr_statement(expr);
                self.p.fixed(";");
            }
            CStmtKind::Assign { target, op, value } => {
                self.p.ident(target);
                self.p.fixed(" ");
                self.p.fixed(op.token());
                self.p.fixed(" ");
                self.expr(value);
                self.p.fixed(";");
            }
            CStmtKind::AssignTo { target, op, value } => {
                self.expr(target);
                self.p.fixed(" ");
                self.p.fixed(op.token());
                self.p.fixed(" ");
                self.expr(value);
                self.p.fixed(";");
            }
            CStmtKind::Inc { target, op } => {
                self.p.fixed(op.token());
                self.p.ident(target);
                self.p.fixed(";");
            }
            CStmtKind::If { branches, else_body } => self.if_stmt(branches, else_body.as_ref()),
            CStmtKind::While { cond, body } => {
                self.p.fixed("while (");
                self.expr(cond);
                self.p.fixed(") ");
                self.block(body);
            }
            CStmtKind::For {
                ty,
                decls,
                cond,
                step,
                body,
            } => {
                self.p.fixed("for (");
                self.ty(ty);
                for (index, decl) in decls.iter().enumerate() {
                    self.p.fixed(if index == 0 { " " } else { ", " });
                    self.p.ident(&decl.name);
                    self.p.fixed(" = ");
                    self.expr(&decl.value);
                }
                self.p.fixed("; ");
                self.expr(cond);
                self.p.fixed("; ");
                self.for_step(step);
                self.p.fixed(") ");
                self.block(body);
            }
            CStmtKind::RangeFor {
                binding,
                style,
                maybe_unused,
                range,
                body,
            } => self.range_for(binding, *style, *maybe_unused, range, body),
            CStmtKind::Switch {
                value,
                cases,
                default,
            } => self.switch(value, cases, default.as_deref()),
            CStmtKind::DoWhile { body, cond } => {
                self.p.fixed("do ");
                self.block(body);
                self.p.fixed(" while (");
                self.expr(cond);
                self.p.fixed(");");
            }
            CStmtKind::Try { body, catches } => self.try_stmt(body, catches),
            CStmtKind::Throw(value) => {
                self.p.fixed("throw");
                if let Some(value) = value {
                    self.p.fixed(" ");
                    self.expr(value);
                }
                self.p.fixed(";");
            }
            CStmtKind::FallThrough => self.p.fixed("[[fallthrough]];"),
            CStmtKind::StaticAssert { cond, message } => {
                self.p.fixed("static_assert(");
                self.expr(cond);
                self.p.fixed(", ");
                self.p.str_lit(message);
                self.p.fixed(");");
            }
            CStmtKind::Break => self.p.fixed("break;"),
            CStmtKind::Continue => self.p.fixed("continue;"),
            CStmtKind::Return(value) => {
                self.p.fixed("return");
                if let Some(value) = value {
                    self.p.fixed(" ");
                    self.expr(value);
                }
                self.p.fixed(";");
            }
            CStmtKind::Seq(stmts) => {
                for (index, stmt) in stmts.iter().enumerate() {
                    if index > 0 {
                        self.p.newline();
                    }
                    self.stmt(stmt);
                }
            }
            CStmtKind::Block(block) => self.block(block),
            CStmtKind::Error => self.p.fixed("/* error */;"),
        }
    }

    /// An expression statement (without the `;`). Long stream chains wrap:
    ///
    /// ```text
    /// std::cout << a << " " << b << …
    ///           << c << '\n';
    /// ```
    fn expr_statement(&mut self, expr: &CExpr) {
        let mut operands = Vec::new();
        stream_operands(expr, &mut operands);
        let start = self.p.position().column as usize;
        let Some((head, rest)) = operands
            .split_first()
            .filter(|_| start + flat_width(expr) > LINE_WIDTH)
        else {
            self.expr(expr);
            return;
        };
        self.expr(head);
        let align = self.p.position().column.saturating_add(1);
        for (index, operand) in rest.iter().enumerate() {
            // ` << operand`, plus the `;` after the last operand.
            let width = 4 + flat_width(operand) + usize::from(index + 1 == rest.len());
            let used = self.p.position().column as usize - 1;
            if index > 0 && used + width > LINE_WIDTH {
                self.p.newline_aligned(align);
                self.p.fixed("<< ");
            } else {
                self.p.fixed(" << ");
            }
            self.expr(operand);
        }
    }

    /// `if (…) { … } else if (…) { … } else { … }`.
    fn if_stmt(&mut self, branches: &[(CExpr, CBlock)], else_body: Option<&CBlock>) {
        for (index, (cond, body)) in branches.iter().enumerate() {
            self.p.fixed(if index == 0 { "if (" } else { " else if (" });
            self.expr(cond);
            self.p.fixed(") ");
            self.block(body);
        }
        if let Some(body) = else_body {
            self.p.fixed(" else ");
            self.block(body);
        }
    }

    /// `for (const auto& x : range) { … }` or
    /// `for (const auto& [k, v] : range) { … }`, with `auto` or `auto&` for a
    /// copy or an editable item, and `[[maybe_unused]]` first when the body
    /// reads none of the names.
    fn range_for(
        &mut self,
        binding: &RangeBinding,
        style: BindingStyle,
        maybe_unused: bool,
        range: &CExpr,
        body: &CBlock,
    ) {
        self.p.fixed("for (");
        if maybe_unused {
            self.p.fixed("[[maybe_unused]] ");
        }
        self.p.fixed(style.prefix());
        match binding {
            RangeBinding::One(name) => self.p.ident(name),
            RangeBinding::Pair(key, value) => {
                self.p.fixed("[");
                self.p.ident(key);
                self.p.fixed(", ");
                self.p.ident(value);
                self.p.fixed("]");
            }
        }
        // ` : ` keeps a range that starts with `::` from lexing as `:::`
        // (spec §6.8.3).
        self.p.fixed(" : ");
        self.expr(range);
        self.p.fixed(") ");
        self.block(body);
    }

    /// `switch (value) { … }`: each `case label:` and `default:` one level
    /// deeper than the `switch`, and the statements under it one level
    /// deeper again.
    fn switch(&mut self, value: &CExpr, cases: &[CCase], default: Option<&[CStmt]>) {
        self.p.fixed("switch (");
        self.expr(value);
        self.p.fixed(") {");
        self.p.newline();
        self.p.indent();
        for case in cases {
            self.p.fixed("case ");
            self.expr(&case.label);
            self.p.fixed(":");
            self.case_body(&case.body);
        }
        if let Some(body) = default {
            self.p.fixed("default:");
            self.case_body(body);
        }
        self.p.dedent();
        self.p.fixed("}");
    }

    /// The statements under a `case` or `default` label, one level deeper. A
    /// body that is one `{ … }` block stays on the label's line:
    /// `case 1: { … }` (w2.md §2.9).
    fn case_body(&mut self, body: &[CStmt]) {
        if let [
            CStmt {
                kind: CStmtKind::Block(block),
                origin,
                comment: None,
            },
        ] = body
        {
            let start = self.p.position();
            self.p.fixed(" ");
            self.block(block);
            if let Some(origin) = origin {
                self.p.map(start, origin);
            }
            self.p.newline();
            return;
        }
        self.p.newline();
        self.p.indent();
        for stmt in body {
            self.stmt(stmt);
            self.p.newline();
        }
        self.p.dedent();
    }

    /// `try { … } catch (const E& e) { … } …`.
    fn try_stmt(&mut self, body: &CBlock, catches: &[CCatch]) {
        self.p.fixed("try ");
        self.block(body);
        for catch in catches {
            let start = self.p.position();
            self.p.fixed(" catch (const ");
            self.ty(&catch.ty);
            self.p.fixed("& ");
            self.p.ident(&catch.name);
            self.p.fixed(") ");
            self.block(&catch.body);
            if let Some(origin) = &catch.origin {
                self.p.map(start, origin);
            }
        }
    }

    /// The third clause of a `for` loop.
    fn for_step(&mut self, step: &ForStep) {
        match step {
            ForStep::Inc(op, name) => {
                self.p.fixed(op.token());
                self.p.ident(name);
            }
            ForStep::Assign(op, name, amount) => {
                self.p.ident(name);
                self.p.fixed(" ");
                self.p.fixed(op.token());
                self.p.fixed(" ");
                self.expr(amount);
            }
        }
    }

    /// An expression, recording a source-map range for each of its origins.
    #[allow(clippy::too_many_lines, reason = "one arm per expression node")]
    fn expr(&mut self, expr: &CExpr) {
        let start = self.p.position();
        match &expr.kind {
            CExprKind::Num(lit) => self.p.num(lit),
            CExprKind::Str(lit) => self.p.str_lit(lit),
            CExprKind::Char(lit) => self.p.char_lit(*lit),
            CExprKind::Fixed(text) => self.p.fixed(text),
            CExprKind::Name(name) => self.p.ident(name),
            CExprKind::Unary { op, operand } => {
                self.p.fixed(op.token());
                self.expr(operand);
            }
            CExprKind::Binary { op, lhs, rhs } => {
                self.expr(lhs);
                self.p.fixed(" ");
                self.p.fixed(op.token());
                self.p.fixed(" ");
                self.expr(rhs);
            }
            CExprKind::Conditional {
                cond,
                then_value,
                else_value,
            } => {
                self.expr(cond);
                self.p.fixed(" ? ");
                self.expr(then_value);
                self.p.fixed(" : ");
                self.expr(else_value);
            }
            CExprKind::Call { callee, args } => {
                match callee {
                    Callee::User(name) => self.p.ident(name),
                    Callee::Fixed(name) => self.p.fixed(name),
                    Callee::Template(name, types) => {
                        self.p.fixed(name);
                        self.p.fixed("<");
                        for (index, ty) in types.iter().enumerate() {
                            if index > 0 {
                                self.p.fixed(", ");
                            }
                            self.ty(ty);
                        }
                        self.p.fixed(">");
                    }
                }
                self.p.fixed("(");
                self.args(args);
                self.p.fixed(")");
            }
            CExprKind::Cast { ty, value } => {
                self.p.fixed("static_cast<");
                self.ty(ty);
                self.p.fixed(">(");
                self.expr(value);
                self.p.fixed(")");
            }
            CExprKind::Method { object, name, args } => {
                self.expr(object);
                self.p.fixed(".");
                self.p.fixed(name);
                self.p.fixed("(");
                for (index, arg) in args.iter().enumerate() {
                    if index > 0 {
                        self.p.fixed(", ");
                    }
                    self.expr(arg);
                }
                self.p.fixed(")");
            }
            CExprKind::Field { object, field } => {
                self.expr(object);
                self.p.fixed(".");
                self.p.ident(field);
            }
            CExprKind::Enumerator { owner, value } => {
                self.qualified(owner);
                self.p.fixed("::");
                self.p.ident(value);
            }
            CExprKind::Index { object, index } => {
                self.expr(object);
                self.p.fixed("[");
                self.expr(index);
                self.p.fixed("]");
            }
            CExprKind::Braces(items) => {
                self.p.fixed("{");
                self.args(items);
                self.p.fixed("}");
            }
            CExprKind::Init { ty, items } => {
                self.ty(ty);
                self.p.fixed("{");
                for (index, (field, value)) in items.iter().enumerate() {
                    if index > 0 {
                        self.p.fixed(", ");
                    }
                    if let Some(field) = field {
                        self.p.fixed(".");
                        self.p.ident(field);
                        self.p.fixed(" = ");
                    }
                    self.expr(value);
                }
                self.p.fixed("}");
            }
            CExprKind::Paren(inner) => {
                self.p.fixed("(");
                self.expr(inner);
                self.p.fixed(")");
            }
            CExprKind::Error => self.p.fixed("0 /* error */"),
        }
        for origin in &expr.origins {
            self.p.map(start, origin);
        }
    }
}

/// The operands of a `<<` chain generated for printing (`std::cout`, then
/// each value), or just `expr` if it is not such a chain.
fn stream_operands<'a>(expr: &'a CExpr, out: &mut Vec<&'a CExpr>) {
    match &expr.kind {
        CExprKind::Binary {
            op: BinOp::Shl,
            lhs,
            rhs,
        } if expr.origins.is_empty() => {
            stream_operands(lhs, out);
            out.push(rhs);
        }
        _ => out.push(expr),
    }
}

/// The length in bytes of an expression printed on one line.
fn flat_width(expr: &CExpr) -> usize {
    match &expr.kind {
        CExprKind::Num(lit) => lit.as_str().len(),
        CExprKind::Str(lit) => lit.to_cpp().len(),
        CExprKind::Char(lit) => lit.to_cpp().len(),
        CExprKind::Fixed(text) => text.len(),
        CExprKind::Name(name) => name.as_str().len(),
        CExprKind::Unary { op, operand } => op.token().len() + flat_width(operand),
        CExprKind::Binary { op, lhs, rhs } => flat_width(lhs) + op.token().len() + 2 + flat_width(rhs),
        CExprKind::Conditional {
            cond,
            then_value,
            else_value,
        } => flat_width(cond) + 3 + flat_width(then_value) + 3 + flat_width(else_value),
        CExprKind::Call { callee, args } => {
            let name = match callee {
                Callee::User(name) => name.as_str().len(),
                Callee::Fixed(name) => name.len(),
                Callee::Template(name, types) => {
                    name.len()
                        + 2
                        + types.iter().map(CType::width).sum::<usize>()
                        + 2 * types.len().saturating_sub(1)
                }
            };
            name + 2 + list_width(args)
        }
        CExprKind::Cast { ty, value } => "static_cast<>()".len() + ty.width() + flat_width(value),
        CExprKind::Method { object, name, args } => {
            flat_width(object)
                + 1
                + name.len()
                + 2
                + args.iter().map(flat_width).sum::<usize>()
                + 2 * args.len().saturating_sub(1)
        }
        CExprKind::Field { object, field } => flat_width(object) + 1 + field.as_str().len(),
        CExprKind::Enumerator { owner, value } => {
            owner.iter().map(|part| part.as_str().len() + 2).sum::<usize>() + value.as_str().len()
        }
        CExprKind::Index { object, index } => flat_width(object) + 2 + flat_width(index),
        CExprKind::Braces(items) => 2 + list_width(items),
        CExprKind::Init { ty, items } => {
            let fields: usize = items
                .iter()
                .map(|(field, value)| {
                    field.as_ref().map_or(0, |field| field.as_str().len() + 4) + flat_width(value)
                })
                .sum();
            ty.width() + 2 + fields + 2 * items.len().saturating_sub(1)
        }
        CExprKind::Paren(inner) => 2 + flat_width(inner),
        CExprKind::Error => "0 /* error */".len(),
    }
}

/// The length of expressions separated by `, `.
fn list_width(items: &[CExpr]) -> usize {
    items.iter().map(flat_width).sum::<usize>() + 2 * items.len().saturating_sub(1)
}


//! The commands through Tauri's IPC, on the mock runtime: every command is
//! registered and answers with typed results or errors, requests are decoded
//! strictly, and build and run sessions stream through real channels in
//! order, ending with exactly one `finished` or `exit` message
//! (`docs/spec/02-architecture.md` §2.5).

#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic, missing_docs)]

mod common;

use std::sync::Arc;

use b2c_ipc::IpcError;
use common::{Harness, NoDialogs, gxx, repo_root, with_printed_text};
use serde_json::{Value, json};
use tauri::ipc::{InvokeBody, InvokeResponseBody};

/// The sample arguments of every command (generated by `b2c-ipc`).
fn samples() -> serde_json::Map<String, Value> {
    let path = repo_root().join("apps/desktop/src-tauri/isolation-tests/samples.generated.json");
    serde_json::from_str(&std::fs::read_to_string(path).unwrap()).unwrap()
}

/// Whether `error` is one of the typed IPC errors (`{ "code": … }`).
fn is_typed(error: &Value) -> bool {
    error["code"]
        .as_str()
        .is_some_and(|code| IpcError::CODES.contains(&code))
}

#[test]
fn every_command_is_registered_and_answers_with_typed_results() {
    let app = Harness::new(Vec::new(), Arc::new(NoDialogs), true);
    let samples = samples();
    assert_eq!(samples.len(), b2c_ipc::COMMAND_NAMES.len());
    for (command, args) in samples {
        // `app_quit` exits the process; the mock runtime cannot.
        if command == "app_quit" {
            continue;
        }
        match app.invoke(&command, args) {
            Ok(response) => assert!(response.is_object(), "{command}: {response}"),
            Err(error) => assert!(is_typed(&error), "{command} gave an untyped error: {error}"),
        }
    }
    let unknown = app.invoke("app_version", json!({})).unwrap_err();
    assert!(!is_typed(&unknown), "{unknown}");
}

